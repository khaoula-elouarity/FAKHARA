export function getAccountError(code, t) {
  const errors = {
    invalid_credentials: t.errInvalidCredentials,
    email_already_registered: t.errEmailExists,
    duplicate_record: t.errEmailExists,
    invalid_or_expired_reset_token: t.errResetToken,
    network_error: t.errNetwork,
    rate_limit_exceeded: t.errRateLimit,
    invalid_email: t.errEmail,
    invalid_phone: t.errPhone,
    invalid_password: t.errPassword,
    invalid_name: t.errName,
    invalid_firstName: t.errName,
    invalid_lastName: t.errName,
    validation_error: t.requiredFields,
    current_password_required: t.errCurrentPassword,
    invalid_newPassword: t.errNewPassword,
    invalid_token: t.errSession,
    account_unavailable: t.errSession,
    invalid_or_expired_token: t.errSession,
    server_error: t.errServer,
    internal_error: t.errServer,
    request_failed: t.errServer,
  };

  return errors[code] || t.errGeneric;
}

export function formatAccountDate(value, language) {
  if (!value) {
    return "—";
  }

  const date = new Date(value);

  if (Number.isNaN(date.getTime())) {
    return "—";
  }

  return new Intl.DateTimeFormat(
    language === "ar" ? "ar-MA" : language === "fr" ? "fr-MA" : "en-MA",
    {
      day: "2-digit",
      month: "long",
      year: "numeric",
    }
  ).format(date);
}

